

CREATE DATABASE IF NOT EXISTS bd_bananos_app
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_general_ci;

USE bd_bananos_app;



CREATE TABLE ped_cliente
(
    I_ID_CLIENTE        INT             NOT NULL AUTO_INCREMENT,
    V_NOMBRE_COMPLETO   VARCHAR(150)    NOT NULL,
    C_CELULAR           CHAR(9)         NOT NULL,
    V_DIRECCION         VARCHAR(250)    NOT NULL,
    V_CORREO            VARCHAR(150)    NOT NULL,
    V_CONTRASENA        VARCHAR(100)    NOT NULL,
    D_FECHA_REGISTRO    DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_PED_CLIENTE PRIMARY KEY (I_ID_CLIENTE),
    CONSTRAINT UQ_CLIENTE_CORREO UNIQUE (V_CORREO)
) ENGINE = InnoDB;



CREATE TABLE ped_categoria
(
    I_ID_CATEGORIA      INT             NOT NULL AUTO_INCREMENT,
    V_NOMBRE            VARCHAR(80)     NOT NULL,
    I_ORDEN             INT             NOT NULL,

    CONSTRAINT PK_PED_CATEGORIA PRIMARY KEY (I_ID_CATEGORIA),
    CONSTRAINT UQ_CATEGORIA_NOMBRE UNIQUE (V_NOMBRE)
) ENGINE = InnoDB;


CREATE TABLE ped_producto
(
    I_ID_PRODUCTO       INT             NOT NULL AUTO_INCREMENT,
    I_ID_CATEGORIA      INT             NOT NULL,
    V_NOMBRE            VARCHAR(120)    NOT NULL,
    V_DESCRIPCION       VARCHAR(300)    NULL,
    V_URL_IMAGEN        VARCHAR(500)    NULL,

    CONSTRAINT PK_PED_PRODUCTO PRIMARY KEY (I_ID_PRODUCTO),
    CONSTRAINT UQ_PRODUCTO_CATEGORIA_NOMBRE UNIQUE (I_ID_CATEGORIA, V_NOMBRE),
    CONSTRAINT FK_PED_PRODUCTO_PED_CATEGORIA
        FOREIGN KEY (I_ID_CATEGORIA) REFERENCES ped_categoria (I_ID_CATEGORIA)
) ENGINE = InnoDB;


CREATE TABLE ped_producto_opcion
(
    I_ID_PRODUCTO_OPCION    INT             NOT NULL AUTO_INCREMENT,
    I_ID_PRODUCTO           INT             NOT NULL,
    V_NOMBRE                VARCHAR(60)     NOT NULL,
    N_PRECIO                DECIMAL(8,2)    NOT NULL,

    CONSTRAINT PK_PED_PRODUCTO_OPCION PRIMARY KEY (I_ID_PRODUCTO_OPCION),
    CONSTRAINT UQ_PRODUCTO_OPCION_PRODUCTO_NOMBRE UNIQUE (I_ID_PRODUCTO, V_NOMBRE),
    CONSTRAINT FK_PED_PRODUCTO_OPCION_PED_PRODUCTO
        FOREIGN KEY (I_ID_PRODUCTO) REFERENCES ped_producto (I_ID_PRODUCTO),
    CONSTRAINT CK_PRODUCTO_OPCION_PRECIO CHECK (N_PRECIO > 0)
) ENGINE = InnoDB;

CREATE TABLE ped_sucursal
(
    I_ID_SUCURSAL       INT             NOT NULL AUTO_INCREMENT,
    V_NOMBRE            VARCHAR(100)    NOT NULL,

    CONSTRAINT PK_PED_SUCURSAL PRIMARY KEY (I_ID_SUCURSAL),
    CONSTRAINT UQ_SUCURSAL_NOMBRE UNIQUE (V_NOMBRE)
) ENGINE = InnoDB;

CREATE TABLE ped_pedido
(
    I_ID_PEDIDO             INT             NOT NULL AUTO_INCREMENT,
    V_CODIGO_PEDIDO         VARCHAR(20)     NULL,
    I_ID_CLIENTE            INT             NOT NULL,
    I_ID_SUCURSAL           INT             NOT NULL,
    C_MODALIDAD             CHAR(1)         NOT NULL,
    C_METODO_PAGO           CHAR(1)         NOT NULL,
    V_DIRECCION_ENTREGA     VARCHAR(250)    NULL,
    N_MONTO_TOTAL           DECIMAL(10,2)   NOT NULL,
    D_FECHA_REGISTRO        DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_PED_PEDIDO PRIMARY KEY (I_ID_PEDIDO),
    CONSTRAINT UQ_PEDIDO_CODIGO_PEDIDO UNIQUE (V_CODIGO_PEDIDO),
    CONSTRAINT FK_PED_PEDIDO_PED_CLIENTE
        FOREIGN KEY (I_ID_CLIENTE) REFERENCES ped_cliente (I_ID_CLIENTE),
    CONSTRAINT FK_PED_PEDIDO_PED_SUCURSAL
        FOREIGN KEY (I_ID_SUCURSAL) REFERENCES ped_sucursal (I_ID_SUCURSAL),
    CONSTRAINT CK_PEDIDO_MODALIDAD CHECK (C_MODALIDAD IN ('R', 'D')),
    CONSTRAINT CK_PEDIDO_METODO_PAGO CHECK (C_METODO_PAGO IN ('E', 'T', 'B')),
    CONSTRAINT CK_PEDIDO_DIRECCION_ENTREGA
        CHECK (C_MODALIDAD = 'R' OR V_DIRECCION_ENTREGA IS NOT NULL),
    CONSTRAINT CK_PEDIDO_MONTO_TOTAL CHECK (N_MONTO_TOTAL > 0)
) ENGINE = InnoDB;


CREATE TABLE ped_pedido_detalle
(
    I_ID_PEDIDO_DETALLE     INT             NOT NULL AUTO_INCREMENT,
    I_ID_PEDIDO             INT             NOT NULL,
    I_ID_PRODUCTO_OPCION    INT             NOT NULL,
    I_CANTIDAD              INT             NOT NULL,
    N_PRECIO_UNITARIO       DECIMAL(8,2)    NOT NULL,
    N_SUBTOTAL              DECIMAL(10,2)   NOT NULL,

    CONSTRAINT PK_PED_PEDIDO_DETALLE PRIMARY KEY (I_ID_PEDIDO_DETALLE),
    CONSTRAINT FK_PED_PEDIDO_DETALLE_PED_PEDIDO
        FOREIGN KEY (I_ID_PEDIDO) REFERENCES ped_pedido (I_ID_PEDIDO),
    CONSTRAINT FK_PED_PEDIDO_DETALLE_PED_PRODUCTO_OPCION
        FOREIGN KEY (I_ID_PRODUCTO_OPCION) REFERENCES ped_producto_opcion (I_ID_PRODUCTO_OPCION),
    CONSTRAINT CK_PEDIDO_DETALLE_CANTIDAD CHECK (I_CANTIDAD > 0),
    CONSTRAINT CK_PEDIDO_DETALLE_PRECIO_UNITARIO CHECK (N_PRECIO_UNITARIO > 0)
) ENGINE = InnoDB;


